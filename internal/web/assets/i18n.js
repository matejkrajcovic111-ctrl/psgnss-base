/* Interface language. English is the source text: t() looks a string up in
   the Slovak table and falls back to the English it was given, so a string
   nobody has translated yet still reads correctly rather than showing a key.

   {name} placeholders are filled from the second argument. A Slovak entry can
   be an array of three plural forms -- 1, 2-4, and everything else -- chosen
   by the placeholder n. The choice is remembered per browser, like the theme,
   and a browser that refuses storage starts in English every time. */
const LANG_KEY = 'psgnss.lang';
const LANGS = ['en', 'sk'];
let LANG = (() => { try { return LANGS.includes(localStorage.getItem(LANG_KEY)) ? localStorage.getItem(LANG_KEY) : 'en'; } catch { return 'en'; } })();

const slovakPlural = n => { n = Math.abs(Number(n)); return n === 1 ? 0 : n >= 2 && n <= 4 ? 1 : 2; };

function t(text, vars) {
  let out = LANG === 'sk' && Object.prototype.hasOwnProperty.call(SK, text) ? SK[text] : text;
  if (Array.isArray(out)) out = out[slovakPlural(vars && vars.n)];
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => Object.prototype.hasOwnProperty.call(vars, k) ? vars[k] : m);
  return out;
}

function setLang(lang) {
  LANG = LANGS.includes(lang) ? lang : 'en';
  try { localStorage.setItem(LANG_KEY, LANG); } catch { /* private window: the choice just does not persist */ }
  document.documentElement.lang = LANG;
  document.title = t('PSGNSSB Base Station');
}

